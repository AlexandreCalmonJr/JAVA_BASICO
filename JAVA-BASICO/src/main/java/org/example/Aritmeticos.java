package org.example;

public class Aritmeticos {
    static void main() {
        //Declaração de Variaveis
        int a = 10;
        int b = 2;

        // Operadores aritmeticos
        int mulitplicar = a * b;
        int dividir = a / b;
        int somar = a + b;
        int subtrair = a - b;

        // Exibindo resultados
        System.out.println("Multiplicar: " + mulitplicar);
        System.out.println("Dividir: " + dividir);
        System.out.println("Somar: " + somar);
        System.out.println("Subtrair: " + subtrair);
         
    }
}
