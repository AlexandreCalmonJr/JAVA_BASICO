package org.example;

public class Relacionais {
    static void main() {
        // Declaração de variaveis
        int a = 10;
        int b = 2;
        int maior;

        // Operadores aritméticos
        if (a > b){
            maior = a;
        } else {
            maior = b;
        }
        // Exibindo resultados
        System.out.println("O maior numero é: " + maior);
    }
}
